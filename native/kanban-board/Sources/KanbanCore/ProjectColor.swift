  /// and with white monogram letters at contrast >= 2.5. Closest pair is 0.055 dEOK (JND ~0.02).
  public static let palette: [OKLCH] = {
    let rows: [(l: Double, c: Double, h: Double)] = [
      (l: 0.62, c: 0.12, h: 0), (l: 0.56, c: 0.15, h: 5), (l: 0.68, c: 0.15, h: 20), (l: 0.62, c: 0.06, h: 20), (l: 0.56, c: 0.06, h: 25),
      (l: 0.62, c: 0.12, h: 30), (l: 0.56, c: 0.15, h: 30), (l: 0.68, c: 0.06, h: 55), (l: 0.68, c: 0.15, h: 55), (l: 0.68, c: 0.15, h: 140),
      (l: 0.62, c: 0.06, h: 140), (l: 0.62, c: 0.15, h: 140), (l: 0.68, c: 0.09, h: 145), (l: 0.56, c: 0.15, h: 145), (l: 0.62, c: 0.12, h: 160),
      (l: 0.56, c: 0.09, h: 165), (l: 0.68, c: 0.12, h: 175), (l: 0.62, c: 0.09, h: 195), (l: 0.68, c: 0.06, h: 210), (l: 0.56, c: 0.06, h: 215),
      (l: 0.68, c: 0.12, h: 220), (l: 0.62, c: 0.12, h: 230), (l: 0.68, c: 0.12, h: 250), (l: 0.62, c: 0.06, h: 250), (l: 0.62, c: 0.15, h: 250),
      (l: 0.56, c: 0.15, h: 250), (l: 0.68, c: 0.15, h: 270), (l: 0.62, c: 0.15, h: 275), (l: 0.56, c: 0.09, h: 275), (l: 0.68, c: 0.06, h: 280),
      (l: 0.68, c: 0.15, h: 295), (l: 0.62, c: 0.12, h: 295), (l: 0.56, c: 0.15, h: 295), (l: 0.62, c: 0.06, h: 315), (l: 0.62, c: 0.15, h: 315),
      (l: 0.56, c: 0.09, h: 320), (l: 0.68, c: 0.15, h: 335), (l: 0.62, c: 0.15, h: 340), (l: 0.56, c: 0.15, h: 340), (l: 0.68, c: 0.09, h: 355)
    ]
    return rows.map { OKLCH(l: $0.l, c: $0.c, h: $0.h) }
  }()
}
